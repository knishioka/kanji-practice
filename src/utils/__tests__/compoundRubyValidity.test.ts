  '小包=こづつみ', // 重箱読み
  '物置=ものおき',
  '福引=ふくび', // 福引き
  '素晴=すば', // 素晴らしい
  '世界中=せかいじゅう', // 中=ジュウ は常用漢字表外の読み
  '田中氏=たなかし',
  '毎朝起=まいあさお', // 毎朝＋起きる
  '五分待=ごふんま', // 五分＋待つ
  '両方見=りょうほうみ', // 両方＋見る
