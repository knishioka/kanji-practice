describe('熟語ルビの読み整合', () => {
  it('例語辞書と一致しない熟語ルビが存在しない', () => {
    const mismatches = detectCompoundRubyIssues()
      .filter((issue) => issue.kind === 'example-mismatch')
      .map(
        (issue) => `${issue.signature} (例語=${issue.expected?.join('/')}) :: ${issue.sentence}`,
      );
    expect(mismatches).toEqual([]);
  });

  it('音訓が混在する熟語ルビは allowlist 済みのものだけ', () => {
    const unexpected = detectCompoundRubyIssues()
      .filter((issue) => issue.kind === 'mixed-reading')
      .filter((issue) => !MIXED_READING_ALLOWLIST.has(issue.signature))
      .map((issue) => `${issue.signature} :: ${issue.sentence}`);
    expect([...new Set(unexpected)]).toEqual([]);
  });

  it('修正済みの誤ルビが再発していない', () => {
    const sentences = allKanji.flatMap((kanji) => kanji.sentences);
    const regressions = BAD_SENTENCE_PATTERNS.filter((pattern) =>
      sentences.some((sentence) => sentence.includes(pattern)),
    );
    expect(regressions).toEqual([]);
  });
});
